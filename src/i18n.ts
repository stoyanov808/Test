export const dictionaries: Record<Language, Record<string, string>> = { bg, en };

/** Missing dynamic keys display their name, making untranslated UI easy to spot. */
export function t(key: string, params: TranslationParams = {}, language: Language = 'bg'): string {
  const text = dictionaries[language][key] ?? dictionaries.bg[key] ?? key;
  const configured: TranslationParams = {
    partyLimit: CONFIG.partyLimit, retriggerLimit: CONFIG.retriggerLimit, autoplayLimit: CONFIG.autoplayLimit,
    ...params,
  };
  return text.replace(/\{(\w+)\}/g, (match, name: string) => String(configured[name] ?? match));
}

export function createTranslator(language: Language): (key: string, params?: TranslationParams) => string {
  return (key, params = {}) => t(key, params, language);
}

/** Receives euros. Integer accounting values should be divided by 100 at this boundary. */
export function formatEuro(value: number, language: Language = 'bg'): string {
  return new Intl.NumberFormat(language === 'bg' ? 'bg-BG' : 'en-IE', {
    style: 'currency', currency: 'EUR', minimumFractionDigits: 2, maximumFractionDigits: 2,
  }).format(value);
}

export function formatEuroCents(cents: number, language: Language = 'bg'): string {
  return formatEuro(cents / 100, language);
}

